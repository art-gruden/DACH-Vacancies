def t(lang: str, key: str, default: str | None = None, **kw) -> str:
    table = LANGS.get(lang) or EN
    text = table.get(key)
    if text is None:
        text = EN.get(key)
    if text is None:
        text = RU.get(key) if lang == "ru" else None
    if text is None:
        return default if default is not None else key
    if kw:
        safe = defaultdict(str, {("from_" if k == "from" else k): v for k, v in kw.items()})
        try:
            return text.format_map(safe)
        except (ValueError, IndexError):
            return text
    return text


